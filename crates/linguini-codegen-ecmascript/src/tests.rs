#[test]
fn project_codegen_emits_schema_namespace_objects() {
    use linguini_ir::{IrMessage, IrModuleBuilder, IrText, IrTextBlockMode, IrTextPart};
    use linguini_syntax::Span;

    fn schema_message(name: &str) -> IrMessage {
        IrMessage {
            name: name.to_owned(),
            docs: Vec::new(),
            parameters: Vec::new(),
            body: None,
        }
    }

    fn locale_message(name: &str, value: &str) -> IrMessage {
        IrMessage {
            name: name.to_owned(),
            docs: Vec::new(),
            parameters: Vec::new(),
            body: Some(IrText {
                parts: vec![IrTextPart::Text(value.to_owned())],
                mode: IrTextBlockMode::Inline,
                span: Span::new(0, value.len()),
            }),
        }
    }

    let schema = IrModuleBuilder::new()
        .push_message(schema_message("checkout.order_ready"))
        .push_message(schema_message("checkout.cart_summary"))
        .build()
        .expect("fixture schema is unique by construction");
    let locale = IrModuleBuilder::new()
        .push_message(locale_message("checkout.order_ready", "Ready"))
        .push_message(locale_message("checkout.cart_summary", "Cart"))
        .build()
        .expect("fixture locale is unique by construction");
    let schema = linguini_ir::SchemaIr::try_from_module(schema)
        .expect("fixture contains only schema declarations");
    let locale = linguini_ir::LocaleIr::try_from_module(locale)
        .expect("fixture contains only locale declarations");

    let files = generate_project_files(
        &schema,
        &[EcmaLocaleModule {
            locale: "en".to_owned(),
            module: locale,
        }],
        &project_options("en"),
    )
    .expect("project codegen");

    let locale_module = files
        .iter()
        .find(|file| file.path == "locales/en.js")
        .expect("locale module");
    assert!(locale_module
        .contents
        .contains("import { checkout } from \"./en/checkout.js\";"));
    assert!(locale_module.contents.contains("  checkout,"));

    let checkout_module = files
        .iter()
        .find(|file| file.path == "locales/en/checkout.js")
        .expect("checkout locale module");
    assert!(checkout_module.contents.contains("order_ready: \"Ready\""));
    assert!(checkout_module.contents.contains("cart_summary: \"Cart\""));

    let declaration = files
        .iter()
        .find(|file| file.path == "locales/en.d.ts")
        .expect("locale declaration");
    assert!(declaration.contents.contains("export { checkout };"));
}

