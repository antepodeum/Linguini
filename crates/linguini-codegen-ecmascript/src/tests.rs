fn generate_project_files(
    schema: &linguini_ir::SchemaIr,
    locales: &[EcmaLocaleModule],
    options: &EcmaProjectOptions,
) -> Result<Vec<EcmaGeneratedFile>, EcmaCodegenError> {
    let project = ValidatedEcmaProject::try_new(schema, locales, options)?;
    crate::generate_project_files(&project)
}

fn project_options(base_locale: &str) -> EcmaProjectOptions {
    EcmaProjectOptions {
        base_locale: Some(base_locale.to_owned()),
        ..EcmaProjectOptions::default()
    }
}

#[test]
fn generated_module_snapshot_is_stable() {
    let schema = parse_schema(include_str!(
        "../../../tests/fixtures/golden/schema/shop.lgs"
    ))
    .expect("schema");
    let locale =
        parse_locale(include_str!("../../../tests/fixtures/golden/locale/ru.lgl")).expect("locale");

    let files = generate_project_files(
        &lower_schema(&schema),
        &[EcmaLocaleModule {
            locale: "ru".to_owned(),
            module: lower_locale(&locale),
        }],
        &EcmaProjectOptions {
            declaration: true,
            tree_shaking: false,
            included_messages: Vec::new(),
            base_locale: Some("ru".to_owned()),
            ..EcmaProjectOptions::default()
        },
    )
    .expect("project files");

    for file in files {
        if file.path == ".gitignore" {
            assert_eq!(file.contents, "# Generated by Linguini. Do not edit.\n*\n");
            continue;
        }
        let snapshot_path = format!("tests/fixtures/golden/snapshots/js-baseline/{}", file.path);
        assert_snapshot(&snapshot_path, &file.contents);
    }
}

